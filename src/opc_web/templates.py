HANDBOOK = """# 员工手册（OPC 角色共同纪律）

本手册是 OPC 所有角色的唯一行为准则。每个角色卡只描述「你是谁、干什么」，
具体怎么做一律以本手册为准。

## 1. 决策与权限
- 不拍板、不花钱、不发布（总决策在 R0 老板）
- 不越权修改他人职责范围；冲突提交 R1 仲裁、R0 裁决

## 2. 读写权限
- 读：知识库全库（知识库/，只读）；《批阅台/批阅台.md》《批阅台/决策日志.md》（只读）
- 写：仅《工作区/<本人角色名>/》及其产出/回报文件
- 公共项目区《项目/》：全员可读；仅「工程」标签角色可写（源码 / 工程性产出落此，见角色卡「标签」）
- 禁止：修改知识库档案、批阅台、他人工作区

## 3. 技能装配
- 技能库在 agents/skills/<技能名>.md；角色卡「## 技能」段登记文件名即装配，派发时按清单注入任务 prompt

## 4. 任务接收与产出
- 任务以「角色卡全文 + 任务」形式接收；工作根目录 = 项目根（路径用 / 分隔）
- 产出先写《工作区/<角色名>/<子任务编号>.md》（编号由中枢给定，如 T-001-S1；边做边追加进度，有输出即视为存活）
- 完成后把同名 <子任务编号>.meta.json 的 status 改为 完成/部分/阻塞（只改这一个字段，其余勿动）

## 5. 回报格式
- 回报结尾用固定小节：## 结论（一两句结果）；## 依据与要点（关键信息/依据/过程）；## 需要 R0 拍板（仅确有需要时写，写清现状/选项/建议）

## 6. 纪律
- 不手写台账表格、不搬运字符串；知识库与批阅台只读
"""


def handbook_text() -> str:
    """《员工手册》正文（bootstrap 写入知识库/员工手册.md，/api/handbook 也返回）。"""
    return HANDBOOK


