def templates() -> list:
    """模板列表（前端选择器 / 引导页展示）。"""
    out = []
    for key, t in PROJECT_TEMPLATES.items():
        out.append({"key": key, "name": t["name"], "desc": t["desc"],
                    "roles": [{"no": r["no"], "name": r["name"], "position": r["position"],
                               "tags": r["tags"]} for r in t["roles"]]})
    return out


def get_template(key: str) -> dict:
    """按 key 取模板；未知 key / 空回退到大型开发项目。"""
    return PROJECT_TEMPLATES.get(key) or PROJECT_TEMPLATES["large_dev"]
