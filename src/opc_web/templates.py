_TPL_FILES = {"回报产出": REPORT_TEMPLATE, "决策建议": ADVICE_TEMPLATE, "每日简报": DAILY_TEMPLATE}


def doc_template(kind: str) -> str:
    """文书模板权威文本（kind ∈ 回报产出 / 决策建议 / 每日简报）。

    _seed/模板-<kind>.md 优先（打包分发可整包替换，同员工手册机制），回退内置常量。
    bootstrap 用它写入每个项目的知识库/OPC 规范/；scheduler 生成简报与决策建议时
    把它注入 prompt —— 改模板即改行为，知识库文件与注入内容同源。"""
    seed = config.BASE / "_seed" / ("模板-" + kind + ".md")
    try:
        if seed.is_file():
            t = config.read_text(seed)
            if t.strip():
                return t
    except Exception:
        pass
    return _TPL_FILES[kind]


